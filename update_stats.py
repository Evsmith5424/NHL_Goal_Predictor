#!/usr/bin/env python3
"""
Pull NHL team stats for this season and last season, blend them,
and write data.js for the NHL Goal Odds page.

Blending: each team's numbers are a weighted mix of the two seasons.
  weight on this season = min(games played this season / RAMP_GAMES, 1)
So with RAMP_GAMES = 25, a team that has played 5 games is 20% this
season and 80% last season. From game 25 on it is 100% this season.

Uses only the Python standard library. Run:  python scripts/update_stats.py
"""
import json
import os
import sys
import urllib.request
from datetime import datetime, timezone

RAMP_GAMES = int(os.environ.get("RAMP_GAMES", "25"))
API = "https://api.nhle.com/stats/rest/en"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data.js")


def fetch_json(url):
    req = urllib.request.Request(url, headers={"User-Agent": "nhl-goal-odds/1.0"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)


def season_ids(today):
    """NHL seasons start in October. From September on, the new season is 'current'."""
    start = today.year if today.month >= 9 else today.year - 1
    return f"{start}{start + 1}", f"{start - 1}{start}"


def season_label(sid):
    return f"{sid[:4]}-{sid[6:]}"


def summary(season_id):
    url = f"{API}/team/summary?cayenneExp=seasonId={season_id}%20and%20gameTypeId=2"
    return {row["teamId"]: row for row in fetch_json(url).get("data", [])}


def blend(cur, prev, w, key):
    if cur is None or cur.get(key) is None:
        return prev[key]
    return w * cur[key] + (1 - w) * prev[key]


def build(cur_id, prev_id, cur_rows, prev_rows, tricodes):
    if len(prev_rows) < 32:
        raise SystemExit(f"Expected 32 teams for {prev_id}, got {len(prev_rows)}. Not updating.")
    teams = []
    for team_id, p in prev_rows.items():
        c = cur_rows.get(team_id)
        gp = c["gamesPlayed"] if c else 0
        w = min(gp / RAMP_GAMES, 1.0) if RAMP_GAMES > 0 else 1.0
        teams.append({
            "ab": tricodes.get(team_id, p["teamFullName"][:3].upper()),
            "name": (c or p)["teamFullName"],
            "gf": round(blend(c, p, w, "goalsForPerGame"), 3),
            "ga": round(blend(c, p, w, "goalsAgainstPerGame"), 3),
            "pp": round(blend(c, p, w, "powerPlayPct") * 100, 1),
            "pk": round(blend(c, p, w, "penaltyKillPct") * 100, 1),
            "pts": c["points"] if c else 0,
            "gp": gp,
            "w": round(w, 3),
            "cur": {"gf": round(c["goalsForPerGame"], 3), "ga": round(c["goalsAgainstPerGame"], 3)} if c else None,
            "prev": {"gf": round(p["goalsForPerGame"], 3), "ga": round(p["goalsAgainstPerGame"], 3), "pts": p["points"]},
        })
    teams.sort(key=lambda t: t["name"])
    meta = {
        "season": season_label(cur_id),
        "lastSeason": season_label(prev_id),
        "rampGames": RAMP_GAMES,
        "updated": datetime.now(timezone.utc).strftime("%Y-%m-%d"),
        "avgGamesPlayed": round(sum(t["gp"] for t in teams) / len(teams), 1),
    }
    return meta, teams


def write(meta, teams):
    lines = [
        "// Generated by scripts/update_stats.py. Edits here are overwritten on the next update.",
        "// gf / ga / pp / pk are blended: w = share from this season, the rest from last season.",
        "const META = " + json.dumps(meta, ensure_ascii=False) + ";",
        "const TEAMS = [",
        *["  " + json.dumps(t, ensure_ascii=False) + "," for t in teams],
        "];",
        "",
    ]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def main():
    cur_id, prev_id = season_ids(datetime.now(timezone.utc))
    tricodes = {t["id"]: t["triCode"] for t in fetch_json(f"{API}/team")["data"]}
    prev_rows = summary(prev_id)
    try:
        cur_rows = summary(cur_id)
    except Exception as e:  # season not started yet, or API hiccup
        print(f"Could not load {cur_id}: {e}. Using last season only.", file=sys.stderr)
        cur_rows = {}
    meta, teams = build(cur_id, prev_id, cur_rows, prev_rows, tricodes)
    write(meta, teams)
    print(f"Wrote {len(teams)} teams. {meta['season']} avg GP {meta['avgGamesPlayed']}, ramp {RAMP_GAMES} games.")


if __name__ == "__main__":
    main()
